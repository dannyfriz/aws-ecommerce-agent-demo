"""Contratos mínimos de persistencia y planificación."""
from typing import Protocol
from .domain import Actor, Order


class Repository(Protocol):
    def get(self, order_id: str) -> Order | None: ...
    def record(self, event: dict) -> None: ...
    def mutate(self, before: Order, after: Order, event: dict) -> None: ...
    def audit(self, limit: int = 50) -> list[dict]: ...
    def pending(self, after: str | None = None, limit: int = 25) -> tuple[list[Order], str | None]: ...


class Planner(Protocol):
    def plan(self, message: str) -> list[dict]: ...


class ToolExecutor(Protocol):
    def execute(self, actor: Actor, action: str, order_id: str, request_id: str) -> dict: ...
