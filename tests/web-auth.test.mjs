import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';

if(!globalThis.crypto)Object.defineProperty(globalThis,'crypto',{value:webcrypto});
const storage=new Map();
globalThis.sessionStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
globalThis.window={APP_CONFIG:{apiBaseUrl:'https://api.example.test',cognitoDomain:'https://login.example.test',clientId:'public',redirectUri:'https://store.example.test/',scope:'openid email profile shop/access',region:'us-east-1'}};
let destination;
globalThis.location={origin:'https://store.example.test',pathname:'/',search:'',assign:value=>{destination=value},replace:value=>{destination=value}};
let historyCleaned=false;
globalThis.history={replaceState:()=>{historyCleaned=true;}};
const auth=await import(new URL('../web/auth.js', import.meta.url));
assert.equal(auth.configuration().clientId,'public');
await auth.signIn();
const url=new URL(destination);
assert.equal(url.searchParams.get('code_challenge_method'),'S256');
assert.equal(url.searchParams.get('response_type'),'code');
assert.equal(url.searchParams.has('client_secret'),false);
const pending=JSON.parse(storage.get('tienda-clara.oauth.pending'));
assert.ok(pending.verifier.length>=43);
assert.equal(url.searchParams.get('state'),pending.state);
location.search=`?code=one-time-code&state=${pending.state}`;
globalThis.fetch=async(endpoint,options)=>{assert.equal(endpoint,'https://login.example.test/oauth2/token');assert.equal(options.body.get('code_verifier'),pending.verifier);assert.equal(options.credentials,'omit');return {ok:true,json:async()=>({access_token:'test-memory-token',refresh_token:'never-stored'})};};
assert.equal(await auth.completeSignIn(),true);
assert.equal(auth.token(),'test-memory-token');
assert.equal(storage.size,0);
assert.ok(historyCleaned);
await auth.signIn();
location.search='?code=malicious&state=wrong';
await assert.rejects(auth.completeSignIn(),/sesión de ingreso/);
assert.equal(storage.size,0);
await auth.signIn();
const expired=JSON.parse(storage.get('tienda-clara.oauth.pending'));
expired.createdAt=Date.now()-600001;
storage.set('tienda-clara.oauth.pending',JSON.stringify(expired));
location.search=`?code=expired&state=${expired.state}`;
await assert.rejects(auth.completeSignIn(),/sesión de ingreso/);
window.APP_CONFIG.redirectUri='https://unrelated.example.test/';
assert.throws(()=>auth.configuration(),/redirección/);
window.APP_CONFIG.redirectUri='https://store.example.test/';
window.APP_CONFIG.apiBaseUrl='http://api.example.test';
assert.throws(()=>auth.configuration(),/HTTPS/);
window.APP_CONFIG.apiBaseUrl='https://api.example.test';
auth.signOut();
assert.equal(auth.token(),null);
assert.equal(new URL(destination).pathname,'/logout');
console.log('PKCE, state, expiración, rechazo de URLs, tokens en memoria y logout: aprobados.');
