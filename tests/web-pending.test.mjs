import assert from 'node:assert/strict';
import {createPendingQueue} from '../web/pending.js';
let session={role:'customer'};
let paused=false;
let reads=0;
let updates=0;
let failures=0;
let resolve;
let lastCursor;
const refresh=createPendingQueue({getSession:()=>session,isPaused:()=>paused,
  readPage:after=>{reads++;lastCursor=after;return new Promise(done=>{resolve=done;});},
  onUpdated:()=>{updates++;},onFailure:()=>{failures++;}});
await refresh();
assert.equal(reads,0);
session={role:'supervisor'};
let running=refresh();
await refresh();
assert.equal(reads,1);
resolve({data:{orders:[{return_status:'REQUESTED'}],next_after:'P-104'}});
await running;
assert.equal(updates,1);
running=refresh('P-104');
resolve({data:{orders:[],next_after:null}});
await running;
running=refresh();
assert.equal(lastCursor,'P-104');
resolve({data:{orders:[{return_status:'REFUNDED'}],next_after:null}});
await running;
assert.equal(failures,1);
assert.equal(updates,2);
running=refresh(null);
session={role:'customer'};
resolve({data:{orders:[],next_after:null}});
await running;
assert.equal(updates,2);
session={role:'supervisor'};
paused=true;
const previous=reads;
await refresh();
assert.equal(reads,previous);
console.log('Pendientes: solo supervisión, paginación, concurrencia, sesión y errores aprobados.');
